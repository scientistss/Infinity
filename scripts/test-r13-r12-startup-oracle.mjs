/** Actual fixed eef startup evidence. No current NPC production imports. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import test from 'node:test';
import { oracle, assertPinnedSource, SOURCE_SHA } from './r13-r12-startup-oracle.mjs';
import { expectedNpcFromR12Snapshot, advanceExpectedNpcWallet } from './r13-compatibility.mjs';
const root = resolve(process.env.R12_ORACLE_SOURCE || '/tmp/infinity-npc-eef-oracle');
assert.ok(process.env.R12_ORACLE_FIXTURE, 'R12_ORACLE_FIXTURE must be generated by the actual eleven old serializers');
const fixture = JSON.parse(readFileSync(process.env.R12_ORACLE_FIXTURE, 'utf8'));
assertPinnedSource(root);
const [save, state, logic, offline] = await Promise.all(['game/save','game/state','game/logic','core/offline'].map(name=>import(pathToFileURL(resolve(root,`src/${name}.ts`)).href)));
const sourceRaw = age => save.exportSave(logic.tick(state.createInitialState(42,43),age),1_792_000_000_000);
async function check(raw, milliseconds) {
  const read=save.importSave(raw), now=read.lastTickAt+milliseconds, result=await oracle(root,raw,now);
  const plain=offline.catchUp(save.deserializeState(read.state),milliseconds/1000);
  assert.equal(result.sourceSha,SOURCE_SHA);
  assert.deepEqual(result.sourceNpc,read.state.npcEconomy);
  assert.deepEqual(result.state,save.serializeState(plain.state));
  assert.equal(result.oldObservedAndUnobservedStateEqual,true);
  assert.equal(result.state.npcEconomy.elapsedSeconds,result.adoptedSegmentsSeconds.reduce((age,step)=>Math.min(11900,age+step),read.state.npcEconomy.elapsedSeconds));
  const migrated=expectedNpcFromR12Snapshot(result.sourceNpc), wallet=advanceExpectedNpcWallet(migrated,result.adoptedSegmentsSeconds);
  assert.deepEqual(migrated.baseline.stock,[Math.min(50000,500+5*read.state.npcEconomy.elapsedSeconds),Math.min(30000,250+2.5*read.state.npcEconomy.elapsedSeconds),Math.min(10000,read.state.npcEconomy.elapsedSeconds)]);
  assert.equal(migrated.now,0);
  return {result,wallet};
}
test('genuine r2 through r12 and paid r5 use untouched source envelopes and actual old startup steps',async()=>{
  for(let revision=2;revision<=12;revision++) {
    assert.equal(fixture.legacySources.find(row=>row.revision===revision)?.generatedBy,'actual source-revision createInitialState/exportSave');
    const raw=JSON.stringify(fixture.legacy[String(revision)]);
    for(const gap of [-1,0,1,381,7200001]) await check(raw,gap);
  }
  await check(JSON.stringify(fixture.paidR5),424);
});
test('actual finite old Number snapshots migrate at now zero before independently replayed continuation',async()=>{
  for(const age of [0,.1+.2,66,11899.875,11900]) for(const gap of [0,381,7200001]) await check(sourceRaw(age),gap);
});
test('r12 capped age cannot stand in for the new wallet clock',async()=>{
  const {result,wallet}=await check(sourceRaw(11900),7200001);
  assert.equal(result.state.npcEconomy.elapsedSeconds,11900);
  assert.ok(wallet.now>7199&&wallet.now<=7200);
  assert.deepEqual(wallet.baseline.stock,[50000,30000,10000]);
});
test('current/future raw revisions and candidate-state arguments are rejected',async()=>{
  const raw=sourceRaw(66), now=JSON.parse(raw).lastTickAt;
  for(const revision of [13,999]) {const value=JSON.parse(raw);value.revision=revision;await assert.rejects(oracle(root,JSON.stringify(value),now));}
  await assert.rejects(oracle(root,raw,now,{candidateState:{}}));
});
